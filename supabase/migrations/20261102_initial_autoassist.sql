create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  role text not null default 'motorist' check (role in ('motorist', 'mechanic')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mechanic_profiles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  garage_name text not null default '',
  location text not null default '',
  services text[] not null default '{}',
  verified boolean not null default false,
  rating numeric(2,1) not null default 0,
  reviews_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vehicles (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  make text not null,
  model text not null,
  year integer not null check (year between 1900 and 2100),
  registration text not null,
  power_source text not null check (power_source in ('Petrol', 'Diesel', 'Hybrid', 'Electric', 'LPG')),
  transmission text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(owner_id, registration)
);

create table if not exists public.repair_requests (
  id uuid primary key default gen_random_uuid(),
  motorist_id uuid not null references public.profiles(id) on delete cascade,
  mechanic_id uuid not null references public.profiles(id) on delete restrict,
  vehicle_id uuid not null references public.vehicles(id) on delete restrict,
  description text not null,
  symptom text not null check (symptom in ('Brakes', 'Engine', 'Electrical', 'Other')),
  location_text text not null,
  latitude double precision,
  longitude double precision,
  preferred_time text not null default 'As soon as possible',
  status text not null default 'requested' check (
    status in (
      'requested', 'accepted', 'en-route', 'arrived', 'inspected', 'quoted',
      'approved', 'repairing', 'repair-complete', 'paid', 'completed', 'cancelled'
    )
  ),
  submitted_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inspections (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null unique references public.repair_requests(id) on delete cascade,
  mechanic_id uuid not null references public.profiles(id) on delete cascade,
  brake_pads text not null,
  brake_discs text not null,
  brake_fluid text not null,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.repair_quotes (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null unique references public.repair_requests(id) on delete cascade,
  mechanic_id uuid not null references public.profiles(id) on delete cascade,
  labour_description text not null,
  labour_amount numeric(12,2) not null check (labour_amount >= 0),
  part_description text not null default '',
  part_amount numeric(12,2) not null default 0 check (part_amount >= 0),
  service_fee numeric(12,2) not null default 0 check (service_fee >= 0),
  total numeric(12,2) generated always as (labour_amount + part_amount + service_fee) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ratings (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null unique references public.repair_requests(id) on delete cascade,
  motorist_id uuid not null references public.profiles(id) on delete cascade,
  mechanic_id uuid not null references public.profiles(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review text,
  created_at timestamptz not null default now()
);

create table if not exists public.repair_events (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.repair_requests(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  status text not null,
  note text,
  created_at timestamptz not null default now()
);

create index if not exists vehicles_owner_id_idx on public.vehicles(owner_id);
create index if not exists repair_requests_motorist_id_idx on public.repair_requests(motorist_id);
create index if not exists repair_requests_mechanic_id_idx on public.repair_requests(mechanic_id);
create index if not exists repair_requests_status_idx on public.repair_requests(status);
create index if not exists inspections_request_id_idx on public.inspections(request_id);
create index if not exists repair_quotes_request_id_idx on public.repair_quotes(request_id);
create index if not exists ratings_mechanic_id_idx on public.ratings(mechanic_id);
create index if not exists repair_events_request_id_idx on public.repair_events(request_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, phone, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    case
      when new.raw_user_meta_data ->> 'role' in ('motorist', 'mechanic')
        then new.raw_user_meta_data ->> 'role'
      else 'motorist'
    end
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

create or replace function public.log_repair_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.status is distinct from new.status then
    insert into public.repair_events (request_id, actor_id, status)
    values (new.id, auth.uid(), new.status);
  end if;
  return new;
end;
$$;

